// Procedural vector icons for upgrade cards and the HUD weapon list.
// Each glyph is drawn with the Renderer's line/polygon primitives so the
// iconography matches the in-game vector aesthetic exactly.

export function drawGlyph(r, name, cx, cy, s, color = 'ui') {
  const L = (x1, y1, x2, y2, w = 2) =>
    r.line(cx + x1 * s, cy + y1 * s, cx + x2 * s, cy + y2 * s, { color, width: w });
  const C = (x, y, rad, w = 2) =>
    r.circle(cx + x * s, cy + y * s, rad * s, { color, width: w });
  const P = (pts, w = 2) =>
    r.polygon(pts.map(([x, y]) => [cx + x * s, cy + y * s]), { color, width: w });

  switch (name) {
    case 'machineGun':
      L(-0.9, 0, 0.9, 0, 2.5); C(0.9, 0, 0.22, 0); C(0.15, 0, 0.16, 0);
      return;
    case 'blaster':
      L(-0.85, 0, 0.6, 0, 3.5); C(0.8, 0, 0.22, 2); C(0.05, 0, 0.16, 0);
      return;
    case 'railgun':
      L(-0.9, -0.3, 0.9, -0.3, 2); L(-0.9, 0.3, 0.9, 0.3, 2); L(-0.9, 0, 0.9, 0, 3.5);
      return;
    case 'gatling':
      L(-0.9, -0.2, 0.9, -0.2, 2.5); L(-0.9, 0.2, 0.9, 0.2, 2.5);
      C(0.9, -0.2, 0.18, 0); C(0.9, 0.2, 0.18, 0);
      return;
    case 'spreadShot':
      L(-0.2, 0, 0.9, 0, 2.5); L(-0.2, 0, 0.9, -0.6, 2); L(-0.2, 0, 0.9, 0.6, 2);
      return;
    case 'vulcanFan':
      L(-0.2, 0, 0.9, 0, 2.5); L(-0.2, 0, 0.9, -0.45, 2);
      L(-0.2, 0, 0.9, 0.45, 2); L(-0.2, 0, 0.9, -0.85, 2); L(-0.2, 0, 0.9, 0.85, 2);
      return;
    case 'orbitalShields':
      C(0, 0, 0.75, 2); C(0, 0, 0.4, 2);
      return;
    case 'titanRings':
      C(0, 0, 0.8, 2); C(0, 0, 0.55, 2); C(0, 0, 0.25, 2);
      return;
    case 'homingMissiles':
      L(-0.8, -0.6, 0.4, -0.6, 2); L(-0.8, 0, 0.4, 0, 2); L(-0.8, 0.6, 0.4, 0.6, 2);
      L(0.4, -0.6, 0.9, -0.6, 2.5); L(0.4, 0, 0.9, 0, 2.5); L(0.4, 0.6, 0.9, 0.6, 2.5);
      return;
    case 'swarm':
      L(-0.6, -0.3, 0.5, -0.5, 2); L(-0.6, -0.3, 0.5, -0.3, 2); L(-0.6, -0.3, 0.5, -0.1, 2);
      L(0.5, -0.5, 0.95, -0.5, 2); L(0.5, -0.3, 0.95, -0.3, 2); L(0.5, -0.1, 0.95, -0.1, 2);
      return;
    case 'laserBeam':
      L(-0.95, 0, 0.95, 0, 4); C(0, 0, 0.2, 0);
      return;
    case 'doomRay':
      L(-0.95, 0, 0.95, 0, 4); L(-0.5, -0.35, 0.5, -0.35, 2);
      return;
    case 'mineLayer':
      C(0, 0, 0.5, 2);
      L(0, -0.5, 0, -0.85, 2); L(0, 0.5, 0, 0.85, 2); L(-0.5, 0, -0.85, 0, 2); L(0.5, 0, 0.85, 0, 2);
      return;
    case 'minefield':
      C(-0.45, 0, 0.35, 2); C(0.45, 0, 0.35, 2);
      L(-0.45, -0.35, -0.45, -0.6, 2); L(0.45, 0.35, 0.45, 0.6, 2);
      return;
    case 'damage':
      L(0, -0.9, 0.55, 0.2, 2.5); L(-0.55, 0.2, 0.55, 0.2, 2.5); L(0, -0.9, -0.55, 0.2, 2.5);
      return;
    case 'fireRate':
      L(-0.6, 0.55, 0.1, -0.55, 2.5); L(0.1, -0.55, 0.55, 0.15, 2.5);
      L(-0.55, 0.15, -0.05, 0.15, 2.5);
      return;
    case 'thrustPower':
      L(-0.6, 0, 0.7, 0, 3); L(0.35, -0.5, 0.7, 0, 2.5); L(0.35, 0.5, 0.7, 0, 2.5);
      return;
    case 'reverseThrust':
      L(0.6, 0, -0.7, 0, 3); L(-0.35, -0.5, -0.7, 0, 2.5); L(-0.35, 0.5, -0.7, 0, 2.5);
      return;
    case 'projectileSpeed':
      L(-0.8, 0, 0.8, 0, 2.5); L(0.5, -0.5, 0.8, 0, 2.5); L(0.5, 0.5, 0.8, 0, 2.5);
      L(-0.4, -0.4, -0.1, -0.1, 2); L(-0.4, 0.4, -0.1, 0.1, 2);
      return;
    case 'area':
      C(0, 0, 0.8, 2); C(0, 0, 0.45, 2); L(0, -0.8, 0, -0.95, 2); L(0, 0.8, 0, 0.95, 2);
      return;
    case 'maxHp':
      L(0, 0.6, -0.6, -0.2, 2.5); L(-0.6, -0.2, -0.2, -0.7, 2.5);
      L(-0.2, -0.7, 0.2, -0.2, 2.5); L(0.2, -0.2, 0.6, -0.7, 2.5); L(0.6, -0.7, 0, 0.6, 2.5);
      return;
    case 'armor':
      P([[-0.6, 0], [0, -0.7], [0.6, 0], [0, 0.7]], 2.5); L(0, -0.7, 0, 0.7, 2);
      return;
    case 'pickupRange':
      L(-0.6, -0.6, -0.6, 0.6, 2.5); L(-0.6, 0.6, 0.2, 0.6, 2.5); L(0.2, 0.6, 0.2, -0.2, 2.5);
      L(0.2, -0.2, 0.7, -0.2, 2.5);
      return;
    case 'luck':
      P([[-0.55, -0.55], [0, 0.55], [0.55, -0.55], [0, -0.05]], 2);
      return;
    case 'critChance':
      L(0, -0.8, 0, -0.1, 2.5); C(0, 0.25, 0.14, 0); L(0, 0.65, 0, 0.8, 2.5);
      return;
    case 'plasmaAura':
      C(0, 0, 0.85, 2); C(0, 0, 0.5, 2);
      L(0, -0.85, 0, -1.0, 2); L(0, 0.85, 0, 1.0, 2); L(-0.85, 0, -1.0, 0, 2); L(0.85, 0, 1.0, 0, 2);
      return;
    case 'arcCoil':
      L(0.2, -0.9, -0.2, 0.1, 2.5); L(-0.2, 0.1, 0.35, 0.1, 2.5); L(0.35, 0.1, -0.35, 0.9, 2.5);
      return;
    case 'splitCore':
      L(-0.9, 0, -0.1, 0, 2.5); L(-0.1, 0, 0.7, -0.6, 2); L(-0.1, 0, 0.7, 0.6, 2);
      return;
    case 'naniteRepair':
      C(0, 0, 0.75, 2); L(-0.4, 0, 0.4, 0, 2.5); L(0, -0.4, 0, 0.4, 2.5);
      return;
    case 'xpGain':
      L(0, 0.8, 0, -0.7, 3); L(-0.55, -0.15, 0, -0.7, 2.5); L(0.55, -0.15, 0, -0.7, 2.5);
      return;
    case 'curse':
      L(0, -0.7, 0.6, 0.5, 2.5); L(0.6, 0.5, -0.6, 0.5, 2.5); L(-0.6, 0.5, 0, -0.7, 2.5);
      L(0, -0.15, 0, 0.25, 2.5); C(0, 0.45, 0.07, 0);
      return;
    default:
      C(0, 0, 0.6, 2);
  }
}
